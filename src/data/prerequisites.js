export function resolvePrerequisites(catalog, sectionId, topicId) {
  const sectionIndex = catalog.sections.findIndex((section) => section.id === sectionId);
  const topicIndex = catalog.sections[sectionIndex]?.topics.findIndex((topic) => topic.id === topicId);
  const refs = prerequisiteRefs[`${sectionIndex}:${topicIndex}`] || [];
  return refs.map(([section, topic]) => ({ section:catalog.sections[section], topic:catalog.sections[section]?.topics[topic] }))
    .filter((entry) => entry.section && entry.topic);
}
